#include "gtest/gtest.h"
#include "odamex.h"
#include "m_fixed.h"

// TODO: tests for overflows, we want to catch things like when some of the 64 bit stuff had accidental conversions to 32 bit

TEST(FixedMath, IntConversion) {
	EXPECT_EQ(FIXED2INT(INT2FIXED(0)), 0);
	EXPECT_EQ(FIXED2INT(INT2FIXED(1)), 1);
	EXPECT_EQ(FIXED2INT(INT2FIXED(2)), 2);
	EXPECT_EQ(FIXED2INT(INT2FIXED(10)), 10);
	EXPECT_EQ(FIXED2INT(INT2FIXED(1234)), 1234);
	EXPECT_EQ(FIXED2INT(INT2FIXED(32767)), 32767);
}

// these are all off by one, is this correct or not?
TEST(FixedMath, NegativeIntConversion) {
	EXPECT_EQ(FIXED2INT(INT2FIXED(-1)), -1);
	EXPECT_EQ(FIXED2INT(INT2FIXED(-2)), -2);
	EXPECT_EQ(FIXED2INT(INT2FIXED(-10)), -10);
	EXPECT_EQ(FIXED2INT(INT2FIXED(-1234)), -1234);
	EXPECT_EQ(FIXED2INT(INT2FIXED(-32768)), -32768);
}

TEST(FixedMath, DoubleConversionRoundUp) {
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(0.6)), 1);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(1.6)), 2);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(2.6)), 3);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(10.6)), 11);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(1234.6)), 1235);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(32766.6)), 32767);
}

TEST(FixedMath, DoubleConversionRoundDown) {
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(0.4)), 0);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(1.4)), 1);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(2.4)), 2);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(10.4)), 10);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(1234.4)), 1234);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(32767.4)), 32767);
}

TEST(FixedMath, NegativeDoubleConversionRoundUp) {
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-1.4)), -1);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-2.4)), -2);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-10.4)), -10);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-1234.4)), -1234);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-32767.4)), -32767);
}

TEST(FixedMath, NegativeDoubleConversionRoundDown) {
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-1.6)), -2);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-2.6)), -3);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-10.6)), -11);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-1234.6)), -1235);
	EXPECT_EQ(FIXED2INT(DOUBLE2FIXED(-32767.6)), -32768);
}