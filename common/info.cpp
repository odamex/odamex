std::string mobjinfo_t::getDisplayName() const
{
	if (!deh_name.empty() && !display_name_set)
		return deh_name;
	if (!display_name.empty())
	{
		return GStrings.maybeLookup(display_name);
	}
	return P_MobjToName(static_cast<mobjtype_t>(this->type));
}

bool mobjinfo_t::isID24Pickup() const
{
	// check that all id24 pickup type and sound fields
	// are set to their defaults
	return
		pickupitem     != id24pickup_t::None or
		pickupweapon   != wp_nochange or
		pickupammo     != am_noammo or
		pickupsound    != nullptr;
}

bool mobjinfo_t::hasWeaponPickup() const
{
	if (isID24Pickup())
		return pickupweapon != wp_nochange;

	return
		type == MT_CHAINGUN or
		type == MT_SHOTGUN or
		type == MT_SUPERSHOTGUN or
		type == MT_MISC25 or
		type == MT_MISC26 or
		type == MT_MISC27 or
		type == MT_MISC28;
}

bool mobjinfo_t::isMonster() const
{
	return flags & MF_COUNTKILL || flags4 & MF4_ISMONSTER;
}

