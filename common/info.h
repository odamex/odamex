inline FArchive &operator<< (FArchive &arc, mobjinfo_t *info)
{
	if (info)
		return arc << static_cast<int32_t>(info->type);
	else
		return arc << static_cast<int32_t>(0xffffffff);
}

inline FArchive &operator>> (FArchive &arc, mobjinfo_t *&info)
{
    int32_t ofs;
    arc >> ofs;
    auto it = mobjinfo.find(ofs);
    if (it != mobjinfo.end())
        info = &it->second;
    else
        info = NULL;
    return arc;
}
